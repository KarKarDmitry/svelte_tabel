async function addEmployees() {
	console.log('👥 Добавление сотрудников...\n');

	const existing = await db.select({ id: schema.employee.id }).from(schema.employee);
	const startNum = existing.length + 1;
	const count = 100;
	const employees = [];

	for (let i = 0; i < count; i++) {
		const num = startNum + i;
		const lastName = lastNames[Math.floor(Math.random() * lastNames.length)];
		const firstName = firstNames[Math.floor(Math.random() * firstNames.length)];
		const middleName = firstNames[Math.floor(Math.random() * firstNames.length)] + 'ович';
		employees.push({
			number: String(num).padStart(3, '0'),
			lastName,
			firstName,
			middleName
		});
	}

	await db.insert(schema.employee).values(employees);
	console.log(`  ✓ Добавлено ${employees.length} сотрудников`);
	console.log(`  Номера: ${employees[0].number} — ${employees[employees.length - 1].number}`);
	process.exit(0);
}

addEmployees().catch((e: any) => {
	console.error('❌ Ошибка:', e.message || e);
	process.exit(1);
});
